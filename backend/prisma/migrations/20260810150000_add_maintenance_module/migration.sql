
CREATE TABLE `maintenance_schedule` (
  `id` INTEGER NOT NULL AUTO_INCREMENT,
  `scheduleNumber` VARCHAR(50) NOT NULL,
  `vehicleId` INTEGER NOT NULL,
  `assignedDriverId` INTEGER NULL,
  `serviceType` VARCHAR(100) NOT NULL,
  `maintenanceCategory` VARCHAR(100) NOT NULL,
  `dueDate` DATETIME(3) NULL,
  `dueMileage` DOUBLE NULL,
  `scheduledDate` DATETIME(3) NOT NULL,
  `estimatedDurationHours` DOUBLE NULL,
  `priority` VARCHAR(191) NOT NULL DEFAULT 'MEDIUM',
  `reason` VARCHAR(500) NOT NULL,
  `description` VARCHAR(5000) NOT NULL,
  `assignedTechnician` VARCHAR(150) NULL,
  `assignedWorkshop` VARCHAR(150) NULL,
  `serviceLocation` VARCHAR(200) NULL,
  `requiredParts` VARCHAR(5000) NULL,
  `estimatedLabourHours` DOUBLE NULL,
  `estimatedPartsCost` DECIMAL(12,2) NULL,
  `estimatedLabourCost` DECIMAL(12,2) NULL,
  `estimatedTotalCost` DECIMAL(12,2) NULL,
  `status` VARCHAR(191) NOT NULL DEFAULT 'SCHEDULED',
  `approvalStatus` VARCHAR(191) NOT NULL DEFAULT 'PENDING',
  `createdBy` VARCHAR(150) NOT NULL,
  `notes` VARCHAR(5000) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  UNIQUE INDEX `maintenance_schedule_scheduleNumber_key` (`scheduleNumber`),
  INDEX `maintenance_schedule_vehicleId_idx` (`vehicleId`),
  INDEX `maintenance_schedule_assignedDriverId_idx` (`assignedDriverId`),
  INDEX `maintenance_schedule_scheduledDate_idx` (`scheduledDate`),
  INDEX `maintenance_schedule_status_idx` (`status`),
  CONSTRAINT `maintenance_schedule_vehicleId_fkey` FOREIGN KEY (`vehicleId`) REFERENCES `vehicle` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `maintenance_schedule_assignedDriverId_fkey` FOREIGN KEY (`assignedDriverId`) REFERENCES `driver` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `work_order` (
  `id` INTEGER NOT NULL AUTO_INCREMENT,
