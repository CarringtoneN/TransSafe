  `faultDescription` VARCHAR(5000) NULL,
  `requestedRepairs` VARCHAR(5000) NULL,
  `priority` VARCHAR(191) NOT NULL DEFAULT 'MEDIUM',
  `estimatedCompletionDate` DATETIME(3) NULL,
  `assignedTechnician` VARCHAR(150) NULL,
  `assignedWorkshop` VARCHAR(150) NULL,
  `supervisor` VARCHAR(150) NULL,
  `requiredSpareParts` VARCHAR(5000) NULL,
  `requiredTools` VARCHAR(5000) NULL,
  `estimatedLabourHours` DOUBLE NULL,
  `estimatedPartsCost` DECIMAL(12,2) NULL,
  `estimatedLabourCost` DECIMAL(12,2) NULL,
  `estimatedTotalCost` DECIMAL(12,2) NULL,
